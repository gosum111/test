function richText(s){
  s=String(s||"");
  if(/<(p|div|h\d|ul|ol|img|a|br|table|strong|b)\b/i.test(s)) return s;
  const e=t=>t.replace(/[&<>"]/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"}[c]));
  let out="",para=[],list=[];
  const flushP=()=>{if(para.length){out+=`<p>${para.map(e).join("<br>")}</p>`;para=[]}};
  const flushL=()=>{
    if(!list.length) return;
    if(list.every(i=>i.includes(":"))) out+=`<div class="timeline">${list.map(i=>{const k=i.indexOf(":");return `<div><b>${e(i.slice(0,k).trim())}</b><p>${e(i.slice(k+1).trim())}</p></div>`}).join("")}</div>`;
    else out+=`<ul>${list.map(i=>`<li>${e(i)}</li>`).join("")}</ul>`;
    list=[];
  };
  s.replace(/\r/g,"").split("\n").forEach(raw=>{
    const l=raw.trim();
    if(!l){flushP();flushL();return}                                   /* บรรทัดว่าง = จบย่อหน้า/รายการ */
    if(l.startsWith("## ")){flushP();flushL();out+=`<h2>${e(l.slice(3))}</h2>`;return}
    if(l.startsWith("- ")){flushP();list.push(l.slice(2).trim());return}
    flushL();para.push(l);
  });
  flushP();flushL();
  return out;
}
